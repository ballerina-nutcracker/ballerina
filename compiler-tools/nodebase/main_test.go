func TestCheckFile(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name   string
		source string
		want   []string
	}{
		{"struct", "type NodeBase struct{}", []string{"NodeBase"}},
		{"alias", "type NodeBase = private", []string{"NodeBase"}},
		{"grouped", "type (NodeBase struct{}; TokenBase = private; Node struct{})", []string{"NodeBase", "TokenBase"}},
		{"generic", "type NodeBase[T any] struct{ Value T }", []string{"NodeBase"}},
		{"interface", "type NodeBase interface{}", []string{"NodeBase"}},
		{"private", "type nodeBase struct{}", nil},
		{"other suffix", "type BaseNode struct{}; type NodeDatabase struct{}", nil},
		{"local", "func f() { type NodeBase struct{} }", nil},
		{"comment and string", "// type NodeBase struct{}\nvar text = `type TokenBase struct{}`", nil},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			fset := token.NewFileSet()
			file, err := parser.ParseFile(fset, "nodes.go", "package nodes\n"+tt.source, parser.SkipObjectResolution)
			if err != nil {
				t.Fatal(err)
			}
			var got []string
			for _, f := range checkFile(fset, file) {
				got = append(got, f.name)
				if f.position.Filename != "nodes.go" || f.position.Line < 2 {
					t.Fatalf("missing source location: %v", f.position)
				}
			}
			if !slices.Equal(got, tt.want) {
				t.Fatalf("got %v; want %v", got, tt.want)
			}
		})
	}
}

func TestDiagnostic(t *testing.T) {
	t.Parallel()
	f := finding{position: token.Position{Filename: "ast/nodes.go", Line: 7, Column: 6}, name: "NodeBase"}
	want := "ast/nodes.go:7:6: nodebase: do not expose Base type NodeBase; keep base types private and expose concrete implementation types instead"
	if got := f.String(); got != want {
		t.Fatalf("got %q; want %q", got, want)
	}
}

func TestScan(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	nested := filepath.Join(root, "nested")
	if err := os.Mkdir(nested, 0o700); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"generated.go", "nodes_test.go", "windows.go"} {
		source := "//go:build windows\n\n// Code generated by test; DO NOT EDIT.\npackage nodes\ntype NodeBase = private\n"
		if err := os.WriteFile(filepath.Join(nested, name), []byte(source), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	findings, err := scan([]string{root})
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 3 {
		t.Fatalf("got %d findings; want 3", len(findings))
	}
	if err := os.WriteFile(filepath.Join(root, "broken.go"), []byte("package"), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := scan([]string{root}); err == nil {
		t.Fatal("malformed source must fail the check")
	}
	if _, err := scan([]string{filepath.Join(root, "missing")}); err == nil {
		t.Fatal("missing directory must fail the check")
	}
}
