package semtypes

type Value struct {
	Value any
}

func newValue(value any) Value {
	return Value{
		Value: value,
	}
}

//shallow:allow shared semantic-value constructor keeps shape and filler construction consistent
func valueFrom(value any) Value {
	return newValue(value)
}
