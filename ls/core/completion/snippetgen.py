"""Generate the completion snippet catalog Go source from snippets.json.

With --check, regenerate in memory and fail if the -out file differs.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

MAX_ENTRIES = 256
FIELDS = ("label", "filter", "insert", "detail", "kind")
KEY_RE = re.compile(r"^[a-z][A-Za-z0-9]*$")
KIND_CONSTANTS = {
    "Snippet": "protocol.CompletionItemKindSnippet",
    "Keyword": "protocol.CompletionItemKindKeyword",
}
GO_ESCAPES = {
    "\a": r"\a", "\b": r"\b", "\f": r"\f", "\n": r"\n",
    "\r": r"\r", "\t": r"\t", "\v": r"\v", '"': r"\"", "\\": r"\\",
}

LICENSE_HEADER = """\
// Copyright (c) 2026, WSO2 LLC. (http://www.wso2.com).
//
// WSO2 LLC licenses this file to you under the Apache License,
// Version 2.0 (the "License"); you may not use this file except in compliance
// with the License.
// You may obtain a copy of the License at
//
// http://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS, WITHOUT
// WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied. See the
// License for the specific language governing permissions and limitations
// under the License.
"""


def generate(src: str) -> bytes:
    entries = decode(src)
    keys = sorted(entries)
    out = [
        LICENSE_HEADER,
        "\n// Code generated by snippetgen. DO NOT EDIT.\n\n",
        "package completion\n\n",
        'import "github.com/ballerina-nutcracker/ballerina/ls/protocol"\n\n',
        "const (\n",
    ]
    for i, key in enumerate(keys):
        out.append(f"{key} snippetID = iota\n" if i == 0 else f"{key}\n")
    out.append(")\n\nvar snippets = [...]snippetDef{\n")
    for key in keys:
        e = entries[key]
        tab_stop = "true" if "${" in e["insert"] else "false"
        out.append(
            f"{key}: {{label: {go_quote(e['label'])}, filter: {go_quote(e['filter'])}, "
            f"insert: {go_quote(e['insert'])}, detail: {go_quote(e['detail'])}, "
            f"kind: {KIND_CONSTANTS[e['kind']]}, tabStop: {tab_stop}}},\n"
        )
    out.append("}\n")
    return gofmt("".join(out).encode())


def decode(src: str) -> dict[str, dict[str, str]]:
    try:
        raw = json.loads(src)
    except json.JSONDecodeError as err:
        raise ValueError(f"decode snippets: {err}") from err
    if not isinstance(raw, dict):
        raise ValueError("decode snippets: top level must be an object")
    if len(raw) > MAX_ENTRIES:
        raise ValueError(f"{len(raw)} entries exceed the limit of {MAX_ENTRIES}")
    entries = {}
    for key, e in raw.items():
        if not KEY_RE.match(key):
            raise ValueError(f"invalid key {key!r}")
        if not isinstance(e, dict):
            raise ValueError(f"{key}: entry must be an object")
        unknown = set(e) - set(FIELDS)
        if unknown:
            raise ValueError(f"{key}: unknown fields {sorted(unknown)}")
        for field in FIELDS:
            if not isinstance(e.get(field, ""), str):
                raise ValueError(f"{key}: {field} must be a string")
        entry = {field: e.get(field, "") for field in FIELDS}
        if entry["kind"] not in KIND_CONSTANTS:
            raise ValueError(f"{key}: invalid kind {entry['kind']!r}")
        if entry["label"] == "":
            raise ValueError(f"{key}: empty label")
        entries[key] = entry
    return entries


def go_quote(s: str) -> str:
    """Quote s as a Go interpreted string literal."""
    parts = []
    for ch in s:
        if ch in GO_ESCAPES:
            parts.append(GO_ESCAPES[ch])
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            parts.append(f"\\x{ord(ch):02x}")
        else:
            parts.append(ch)
    return '"' + "".join(parts) + '"'


def gofmt(src: bytes) -> bytes:
    result = subprocess.run(["gofmt"], input=src, capture_output=True, check=False)
    if result.returncode != 0:
        raise ValueError(f"gofmt: {result.stderr.decode().strip()}")
    return result.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-in", dest="in_path", default="snippets.json",
                        help="path to the snippet catalog JSON")
    parser.add_argument("-out", dest="out_path", default="snippet_gen.go",
                        help="path of the generated Go file")
    parser.add_argument("--check", action="store_true",
                        help="fail if -out differs from the generated source")
    args = parser.parse_args()

    try:
        generated = generate(Path(args.in_path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as err:
        print(f"snippetgen: {err}", file=sys.stderr)
        return 1

    out_path = Path(args.out_path)
    if not args.check:
        out_path.write_bytes(generated)
        return 0
    if out_path.exists() and out_path.read_bytes() == generated:
        return 0
    print(f"snippetgen: {out_path} differs from {args.in_path}; "
          "run go generate ./ls/core/completion", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
